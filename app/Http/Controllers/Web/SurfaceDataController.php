    /**
     * Name → catalog identity for the prototype cart, which only carries the displayed name and price
     * (`addToCart(name, price)`): every plan and product name maps to `{product_key, plan_key}` so the checkout
     * seam can turn the cart into real SKUs. Keys are lower-cased display names; `name|price` variants disambiguate.
     */
    private function skuIndex(string $locale): array
    {
        $index = [];
        foreach ($this->catalog->publicCatalog($locale, 'CZK') as $product) {
            $plans = (array) ($product['plans'] ?? []);
            $cheapest = null;
            foreach ($plans as $plan) {
                $price = isset($plan['price']['month']) ? (int) round(self::amount($plan['price']['month'])) : null;
                $entry = ['product_key' => $product['key'], 'plan_key' => $plan['key'], 'price' => $price, 'price_year' => self::yearlyPrice($plan)];
                $index[mb_strtolower((string) $plan['name'])] = $entry;
                if (($product['family'] ?? null) === 'game') { // the game landing's cards add to the cart as "Gamehosting <plan>" / "Game hosting <plan>"
                    foreach (['gamehosting ', 'game hosting '] as $prefix) {
                        $index[$prefix.mb_strtolower((string) $plan['name'])] = $entry;
                        if ($price !== null) {
                            $index[$prefix.mb_strtolower((string) $plan['name']).'|'.$price] = $entry;
                        }
                    }
                }
                $index[mb_strtolower((string) $product['name'].' '.$plan['name'])] = $entry;
                $index[mb_strtolower((string) $product['name'].' · '.$plan['name'])] = $entry; // product pages add `crumb · plan`
                if ($price !== null) {
                    $index[mb_strtolower((string) $product['name'].' · '.$plan['name']).'|'.$price] = $entry;
                }
                if ($price !== null) {
                    $index[mb_strtolower((string) $plan['name']).'|'.$price] = $entry;
                }
                if ($cheapest === null || ($price !== null && $price < ($cheapest['price'] ?? PHP_INT_MAX))) {
                    $cheapest = $entry;
                }
            }
            if ($cheapest !== null) {
                $index[mb_strtolower((string) $product['name'])] = $cheapest;
                $index[mb_strtolower((string) $product['key'])] = $cheapest;
            }
        }

        return $index;
    }

    /** Commercial rules the cart applies (seam #24): commitment discounts (none unless staff approved one), product → family, active domain discounts. */
    private function pricingRows(): array
    {
        $rules = app(PricingRules::class);
        $families = [];
        foreach (Product::query()->where('state', 'active')->get(['key', 'family']) as $product) {
            $families[$product->key] = $product->family;
        }
        $domain = [];
        foreach (array_keys($rules->domainDiscounts()) as $tld) {
            $d = $rules->domainDiscount($tld, 'register');
            if ($d['percent'] > 0) {
                $domain[$tld] = ['register' => $d['percent'], 'label' => $d['label']];
            }
        }

        return ['commit' => $rules->commitDiscounts(), 'months' => PricingRules::COMMIT_MONTHS, 'product_families' => $families, 'domain_discounts' => $domain];
    }

    /** @var array<string, array<string, array<string,mixed>>> */
    private array $addonCache = [];

    /**
     * Per-product add-ons for the cart and the product pages (seam #24): priced options (sliders, switches, selects) and
     * the add-on products staff allow next to the product, each with its plans and monthly prices. Keyed by product key.
     *
     * @return array<string, array{options: list<array<string,mixed>>, products: list<array<string,mixed>>}>
     */
    private function addonRows(string $locale): array
    {
        if (isset($this->addonCache[$locale])) {
            return $this->addonCache[$locale];
        }
        $rules = app(PricingRules::class);
        $catalog = collect($this->catalog->publicCatalog($locale, 'CZK'))->keyBy('key');
        $out = [];
        foreach ($this->catalog->products() as $product) {
            $options = [];
            foreach ($product->options->sortBy('sort') as $option) {
                $options[] = [
                    'key' => $option->key, 'kind' => $option->kind, 'label' => (string) ($option->label[$locale] ?? $option->label['cs'] ?? $option->key), 'desc' => (string) (data_get($option->meta, "desc.{$locale}") ?? data_get($option->meta, 'desc.cs') ?? ''), 'unit' => $option->unit,
                    'min' => $option->min !== null ? (float) $option->min : null, 'max' => $option->max !== null ? (float) $option->max : null, 'step' => $option->step !== null ? (float) $option->step : null, 'default' => $option->default_value !== null ? (float) $option->default_value : null,
                    'price' => ((int) ($option->price_per_unit_minor['CZK'] ?? 0)) / 100,
                    'choices' => array_values(array_map(fn ($c) => ['key' => (string) $c['key'], 'label' => is_array($c['label'] ?? null) ? (string) ($c['label'][$locale] ?? $c['label']['cs'] ?? $c['key']) : (string) ($c['label'] ?? $c['key']), 'units' => (float) ($c['units'] ?? 0)], (array) ($option->choices ?? []))),
                ];
            }
            $products = [];
            foreach ($rules->addonProducts($product) as $key) {
                $addon = $catalog->get($key);
                if ($addon === null) {
                    continue;
                }
                $yearly = (($addon['meta'] ?? [])['billing_unit'] ?? null) === 'year';
                $plans = [];
                foreach ((array) $addon['plans'] as $plan) {
                    $month = isset($plan['price']['month']) ? self::amount($plan['price']['month']) : 0.0;
                    if ($month <= 0) {
                        continue;
                    }
                    $plans[] = ['key' => $plan['key'], 'name' => (string) $plan['name'], 'price' => $yearly ? (int) round($month * 12) : (float) round($month, 2), 'unit_year' => $yearly, 'desc' => (string) $plan['description']];
                }
                if ($plans === []) {
                    continue;
                }
                $products[] = ['key' => $key, 'name' => (string) $addon['name'], 'desc' => (string) $addon['description'], 'family' => $addon['family'], 'plans' => $plans];
            }
            if ($options === [] && $products === []) {
                continue;
            }
            $out[$product->key] = ['options' => $options, 'products' => $products];
        }

        return $this->addonCache[$locale] = $out;
    }

    /** Sold TLDs with CZK prices for the public domain search (the most wanted first). @return list<array<string,mixed>> */
    private function tldRows(string $locale): array
    {
        $rules = app(PricingRules::class);
        $first = array_values((array) config('onhost.content.domain_page_tlds', ['cz', 'com', 'eu']));
        $rows = [];
        foreach ($this->catalog->tlds() as $policy) {
            try {
                $price = $this->catalog->domainPrice($policy->tld, 'CZK');
            } catch (DomainError) {
                continue;
            }
            $d = $rules->domainDiscount($policy->tld, 'register');
            $rows[] = ['tld' => $policy->tld, 'register' => self::amount($price->register()), 'renew' => self::amount($price->renew()), 'transfer' => self::amount($price->transfer()), 'periods' => (array) ($policy->periods ?: [1]), 'default_period' => (int) $policy->default_period, 'discount' => $d['percent'], 'discount_label' => $d['label'], 'dnssec' => (bool) $policy->dnssec_supported];
        }
        usort($rows, function ($a, $b) use ($first) {
            $ia = array_search($a['tld'], $first, true);
            $ib = array_search($b['tld'], $first, true);

            return [$ia === false ? PHP_INT_MAX : $ia, $a['tld']] <=> [$ib === false ? PHP_INT_MAX : $ib, $b['tld']];
        });

        return $rows;
    }

