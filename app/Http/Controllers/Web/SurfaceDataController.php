    private const CATEGORY = ['web' => 'web', 'managed' => 'firm', 'apps' => 'dev', 'cloud' => 'dev', 'game' => 'game', 'mail' => 'firm', 'addon' => 'firm', 'ai' => 'dev'];

    public function __construct(private readonly CatalogService $catalog, private readonly ContentService $content, private readonly IncidentService $incidents) {}

    public function data(): Response
    {
        $js = Cache::remember('surfaces:onhost-data.js', 60, function () {
            $payload = [];
            foreach (['cs', 'en'] as $locale) {
                $payload[$locale] = [
                    'catalog' => $this->catalogRows($locale), 'plans' => $this->planRows($locale), 'compare' => (array) config("onhost.content.compare.{$locale}", []),
                    'status' => $this->statusRows($locale), 'locations' => $this->content->locations($locale), 'changelog' => $this->content->changelog($locale),
                    'skus' => $this->skuIndex($locale), 'pages' => $this->pageRows($locale), 'webPlans' => $this->webPlanRows($locale), 'gameSlots' => $this->gameSlotRows(),
                    'pricing' => $this->pricingRows(), 'addons' => $this->addonRows($locale), 'tlds' => $this->tldRows($locale),
                ];
            }
            $json = json_encode($payload, JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES | JSON_HEX_TAG);

            return "// Generated by ONhost from the catalog, status page and content — same shapes as the prototype onhost-data.js.\n"
                ."window.ONHOST_DATA = (function () {\n  var D = {$json};\n  function L(cs) { return cs ? D.cs : D.en; }\n"
                ."  return {\n    catalog: function (cs) { return L(cs).catalog; },\n    plans: function (cs) { return L(cs).plans; },\n    compare: function (cs) { return L(cs).compare; },\n"
                ."    status: function (cs) { return L(cs).status; },\n    locations: function (cs) { return L(cs).locations; },\n    changelog: function (cs) { return L(cs).changelog; },\n    skus: function (cs) { return L(cs).skus; },\n    pages: function (cs) { return L(cs).pages; },\n    webPlans: function (cs) { return L(cs).webPlans; },\n    gameSlots: function (cs) { return L(cs).gameSlots; },\n    pricing: function (cs) { return L(cs).pricing; },\n    addons: function (cs) { return L(cs).addons; },\n    tlds: function (cs) { return L(cs).tlds; },\n    generatedAt: ".json_encode(now()->toIso8601String())."\n  };\n})();\n";
        });

        return response($js, 200, ['Content-Type' => 'text/javascript; charset=utf-8', 'Cache-Control' => 'public, max-age=60']);
    }

    /** Public product page slug (onhost-svc-*.js) → catalogue products whose plans the page sells. */
    private const PAGE_PRODUCTS = [
        'web-hosting' => ['web-hosting'], 'wordpress' => ['wordpress'], 'eshop' => ['eshop'], 'mail' => ['mail'], 'database' => ['database'], 'backup' => ['backup-plus', 'backup-hourly'],
        'vps' => ['vps'], 'dedicated' => ['vds'], 'ssl' => ['ssl'], 'cdn' => ['cdn'], 'devhosting' => ['apps'], 'gamehosting' => ['game'],
