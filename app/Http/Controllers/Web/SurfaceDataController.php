    {
        $cs = $locale !== 'en';
        $plans = [];
        foreach ((array) config('onhost.content.domain_page_tlds', ['cz', 'com', 'eu']) as $i => $tld) {
            try {
                $policy = $this->catalog->tld($tld);
                $price = $this->catalog->domainPrice($tld, 'CZK');
            } catch (DomainError) {
                continue;
            }
            $register = self::amount($price->register());
            $plans[] = [
                'name' => '.'.$policy->tld, 'tag' => $i === 0 ? ($cs ? 'Nejžádanější' : 'Most wanted') : '', 'price' => 0, 'unitYear' => true,
                'priceLabel' => number_format($register, 0, ',', ' ').' Kč', 'priceNote' => ($cs ? '/ rok · s DPH ' : '/ year · incl. VAT ').number_format($register * 1.21, 0, ',', ' ').' Kč'.($cs ? ' · obnova ' : ' · renewal ').number_format(self::amount($price->renew()), 0, ',', ' ').($cs ? ' Kč / rok' : ' Kč / year'),
                'ctaLabel' => $cs ? 'Ověřit dostupnost' : 'Check availability', 'goto' => 'home',
                'specs' => array_values(array_filter([
                    $cs ? 'Registrace na rok' : 'One-year registration', $cs ? 'DNS hosting v ceně' : 'DNS hosting included', $policy->dnssec_supported ? 'DNSSEC' : null,
