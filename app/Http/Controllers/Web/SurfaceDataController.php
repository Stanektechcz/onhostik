                ])),
            ];
        }

        return ['plans' => $plans, 'keep_last' => 1];
    }

    /**
     * Game hosting landing cards (`gameSlots`, the prototype's shape with both locales in one row: `{p, hi, cs: [name, badge,
     * tagline, 4 bullets], en: […]}`) from the game product, so the landing sells the same plans as the wizard and the cart.
     *
     * @return list<array{p:int,hi:bool,cs:array<int,mixed>,en:array<int,mixed>}>
     */
    private function gameSlotRows(): array
    {
        $key = (string) config('onhost.content.game_product', 'game');
        $products = [];
        foreach (['cs', 'en'] as $locale) {
            $products[$locale] = collect($this->catalog->publicCatalog($locale, 'CZK'))->firstWhere('key', $key);
        }
        if ($products['cs'] === null) {
            return [];
        }
        $card = function (array $plan, string $locale): array {
            $features = (array) ($plan['features'] ?? []);
            $feats = array_values(array_map('strval', (array) ($features[$locale] ?? (array_is_list($features) ? $features : []))));

            return [(string) $plan['name'], $plan['highlighted'] ? ($locale === 'cs' ? 'Nejčastější volba' : 'Most chosen') : '', (string) ($plan['description'] ?? ''), array_slice($feats === [] ? CatalogPresentation::bullets((array) $plan['entitlements'], 'game', $locale, 4) : $feats, 0, 4)];
        };
        $rows = [];
        foreach (array_values((array) ($products['cs']['plans'] ?? [])) as $i => $plan) {
            $en = (array) ((array_values((array) ($products['en']['plans'] ?? [])))[$i] ?? $plan);
            $rows[] = ['p' => (int) round(isset($plan['price']['month']) ? self::amount($plan['price']['month']) : 0.0), 'hi' => (bool) $plan['highlighted'], 'cs' => $card($plan, 'cs'), 'en' => $card($en, 'en')];
        }

        return $rows;
    }

