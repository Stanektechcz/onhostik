    /**
     * Fakturace tab (api/onhost-panel-billing.api.js): the organization's most relevant document — the open one due first,
     * otherwise the latest settled one — with its lines, the bank details for transfers, the customer identity and the
     * monthly cost breakdown of the active subscriptions. Amounts are decimals; the panel formats money in its own currency/locale.
     */
    private function billing(string $organizationId, $services, bool $cs): array
    {
        $organization = Organization::query()->find($organizationId);
        $fmt = fn ($date) => $date === null ? null : Carbon::parse($date)->format($cs ? 'j. n. Y' : 'j M Y');
        $dec = fn (int|float $minor) => round($minor / 100, 2);
        $trim = fn ($n) => rtrim(rtrim(number_format((float) $n, 4, '.', ''), '0'), '.');
        $documents = Invoice::query()->where('organization_id', $organizationId)->whereIn('type', ['invoice', 'proforma'])->whereNotNull('number');
        $document = (clone $documents)->whereIn('state', [Invoice::ISSUED, Invoice::OVERDUE])->orderBy('due_at')->orderByDesc('issued_at')->first()
            ?? (clone $documents)->whereIn('state', [Invoice::PAID, Invoice::CREDITED])->orderByDesc('issued_at')->first();
        $seller = (array) ($document?->seller ?? []);
        if ($seller === []) {
            $entity = LegalEntity::query()->orderBy('key')->first();
            $seller = $entity === null ? [] : ['iban' => $entity->iban, 'bic' => $entity->bic, 'bank_account' => $entity->bank_account];
        }

        $doc = null;
        if ($document !== null) {
            $lines = $document->lines()->get();
            $from = $lines->min('period_from');
            $to = $lines->max('period_to');
            $overdue = $document->state === Invoice::OVERDUE || ($document->state === Invoice::ISSUED && $document->due_at !== null && $document->due_at->isPast());
            $previous = (clone $documents)->where('id', '!=', $document->id)->where('issued_at', '<', $document->issued_at)->orderByDesc('issued_at')->first();
            $buyer = (array) ($document->buyer ?? []);
            $doc = [
                'id' => $document->id, 'number' => $document->number, 'type' => $document->type, 'currency' => $document->currency,
                'state' => match (true) {
                    $document->state === Invoice::PAID => 'paid', $document->state === Invoice::CREDITED => 'credited', $document->state === Invoice::CANCELLED => 'cancelled', $overdue => 'overdue', default => 'due'
                },
                'issued' => $fmt($document->issued_at), 'due' => $fmt($document->due_at), 'paid' => $fmt($document->paid_at), 'period' => $from && $to ? $fmt($from).' – '.$fmt($to) : null,
                'lines' => $lines->map(fn ($l) => [
                    'name' => $l->description,
                    'sub' => implode(' · ', array_filter([$l->period_from && $l->period_to ? $fmt($l->period_from).' – '.$fmt($l->period_to) : null, $l->sku, ($cs ? 'DPH ' : 'VAT ').$trim($l->tax_rate).' %'])),
                    'qty' => $trim($l->qty).' '.$l->unit, 'unit' => $dec((int) $l->unit_net_minor), 'total' => $dec((int) $l->net_minor),
                ])->values()->all(),
                'subtotal' => $dec((int) $document->subtotal_minor), 'discount' => $dec((int) $document->discount_minor), 'tax' => $dec((int) $document->tax_minor), 'total' => $dec((int) $document->total_minor),
                'paid_amount' => $dec((int) $document->paid_minor), 'outstanding' => $dec(max(0, (int) $document->total_minor - (int) $document->paid_minor)),
                'tax_rates' => collect($document->tax_summary ?? [])->pluck('rate')->filter(fn ($r) => $r !== null)->map($trim)->unique()->values()->all(),
                'payment_reference' => $document->payment_reference, 'payment_method' => $document->payment_method,
                'buyer' => ['name' => $buyer['name'] ?? null, 'ico' => $buyer['ico'] ?? null, 'vat_id' => $buyer['vat_id'] ?? ($buyer['dic'] ?? null), 'email' => $buyer['email'] ?? null],
                'previous' => $previous === null ? null : ['number' => $previous->number, 'state' => $previous->state === Invoice::PAID ? 'paid' : 'open', 'paid' => $fmt($previous->paid_at)],
            ];
        }

        // monthly spend per group of the active subscriptions, grouped the way the panel groups services
        $family = $services->pluck('family', 'id');
        $groups = [];
        foreach (Subscription::query()->where('organization_id', $organizationId)->where('state', Subscription::ACTIVE)->get() as $sub) {
            $key = $sub->domain_id !== null ? 'domain' : match ($family->get($sub->service_id)) {
                'cloud' => 'cloud', 'game' => 'game', 'web', 'managed', 'apps' => 'web', 'mail' => 'mail', 'addon' => 'addon', default => 'other'
            };
            $monthly = $sub->period === 'year' ? intdiv((int) $sub->amount_minor, 12) : (int) $sub->amount_minor;
            $groups[$key] = ['key' => $key, 'count' => ($groups[$key]['count'] ?? 0) + 1, 'amount' => ($groups[$key]['amount'] ?? 0) + $monthly];
        }
        $breakdown = array_values(array_map(fn ($g) => ['key' => $g['key'], 'count' => $g['count'], 'amount' => $dec($g['amount'])], $groups));
        usort($breakdown, fn ($a, $b) => $b['amount'] <=> $a['amount']);

        // what was actually invoiced (tax documents only): the six-month average for the "Průměr 6 měsíců" stat and the
        // twelve-month "Náklady podle služeb" chart — columns are percent heights [label, servers, hosting, other]
        $taxDocuments = Invoice::query()->where('organization_id', $organizationId)->where('type', 'invoice')->whereIn('state', [Invoice::ISSUED, Invoice::OVERDUE, Invoice::PAID])
            ->where('issued_at', '>=', now()->subMonths(11)->startOfMonth())->with('lines')->get();
        $invoiced = (int) $taxDocuments->filter(fn ($i) => $i->issued_at >= now()->subMonths(6)->startOfMonth())->sum('total_minor');
        $groupOf = fn ($line): string => match (true) {
