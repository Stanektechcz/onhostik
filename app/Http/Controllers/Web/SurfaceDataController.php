    /**
     * Plans, prices, specs and the comparison table of every public product page that has catalogue products behind it
     * (`api/onhost-svc-pages.api.js`, seam #23). Every plan carries its SKU so the checkout maps it without guessing.
     *
     * @return array<string, array<string,mixed>>
     */
    private function pageRows(string $locale): array
    {
        $cs = $locale !== 'en';
        $catalog = collect($this->catalog->publicCatalog($locale, 'CZK'))->keyBy('key');
        $out = [];
        foreach (self::PAGE_PRODUCTS as $slug => $keys) {
            $plans = [];
            $compare = [];
            $family = 'web';
            foreach ($keys as $key) {
                $product = $catalog->get($key);
                if ($product === null) {
                    continue;
                }
                $family = (string) $product['family'];
                $yearly = (($product['meta'] ?? [])['billing_unit'] ?? null) === 'year';
                foreach ((array) $product['plans'] as $plan) {
                    $month = isset($plan['price']['month']) ? self::amount($plan['price']['month']) : 0.0;
                    $features = (array) ($plan['features'] ?? []);
                    $specs = array_values(array_map('strval', (array) ($features[$locale] ?? (array_is_list($features) ? $features : []))));
                    $plans[] = [
                        'name' => (string) $plan['name'], 'tag' => $plan['highlighted'] ? ($cs ? 'Nejoblíbenější' : 'Most popular') : ($plan['sla_class'] === 'ha' ? 'SLA 99,99 %' : ''),
                        'price' => $yearly ? (int) round($month * 12) : (float) round($month, 2), 'unitYear' => $yearly ?: null,
                        'specs' => $specs === [] ? CatalogPresentation::bullets((array) $plan['entitlements'], $family, $locale, 6) : $specs,
                        'sku' => ['product_key' => $product['key'], 'plan_key' => $plan['key'], 'price_year' => self::yearlyPrice($plan)],
                    ];
                    $compare[] = ['name' => (string) $plan['name'], 'entitlements' => (array) $plan['entitlements']];
                }
            }
            if ($plans === []) {
                // a page whose products exist but are not on sale (draft, e.g. Apps without an operated executor): the narrated
                // plans lose their prices and their order buttons become a contact request (api/onhost-svc-pages.api.js)
                if (Product::query()->whereIn('key', $keys)->exists()) {
                    $out[$slug] = [
                        'unavailable' => true, 'kicker' => $cs ? 'Zatím nenabízíme · připravujeme' : 'Not on offer yet · in preparation', 'label' => $cs ? 'připravujeme' : 'coming soon',
                        'note' => $cs ? 'Tuto službu zatím neprodáváme. Ozvěte se a dáme vám vědět, jakmile bude v nabídce.' : 'This service is not sold yet. Get in touch and we will tell you when it is available.',
                        'cta' => $cs ? 'Nezávazně poptat' : 'Request it',
                    ];
                }

                continue;
            }
            $out[$slug] = array_filter([
                'plans' => $plans, 'cmp' => ['cols' => array_map(fn ($p) => $p['name'], $compare), 'rows' => CatalogPresentation::compareRows($compare, $family, $locale)],
                'keep_first' => $slug === 'ssl' ? 1 : null, // the free DV certificate stays as authored
            ], fn ($v) => $v !== null);
            // the detailed configuration listing, the per-item add-ons of the page's main product and (web hosting) the configurator
            $out[$slug]['details'] = ['cols' => array_map(fn ($p) => $p['name'], $compare), 'rows' => CatalogPresentation::detailRows($compare, $family, $locale)];
            $addons = $this->addonRows($locale);
            if (isset($addons[$keys[0]])) {
                $out[$slug]['addons'] = $addons[$keys[0]];
            }
            if ($slug === 'web-hosting') {
                $out[$slug]['builder'] = $this->builderRows($locale);
            }
        }
        $out['domains'] = $this->domainPageRows($locale);

        return $out;
    }

    /** Domains page: the most wanted TLDs with the catalogue prices; the CTA checks availability instead of adding a name-less domain to the cart. */
