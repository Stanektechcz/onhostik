    /** The yearly list price of a public-catalogue plan in major units (the cart shows it for a 12- or 24-month term), null when the plan is monthly only. */
    private static function yearlyPrice(array $plan): ?float
    {
        return isset($plan['price_year']['year']) ? (float) round(self::amount($plan['price_year']['year']), 2) : null;
    }

    /** Money value object, its JSON form `{minor, currency, decimal}` or a plain number → float amount. */
    private static function amount(mixed $value): float
    {
        if ($value instanceof Money) {
            return (float) $value->toDecimal();
        }
        if (is_array($value)) {
            return (float) ($value['decimal'] ?? (isset($value['minor']) ? $value['minor'] / 100 : 0));
        }

        return (float) $value;
    }

