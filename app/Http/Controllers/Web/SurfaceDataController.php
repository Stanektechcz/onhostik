    /** Orderable products and plans for the panel's "Nová služba" wizard (api/onhost-panel-order.api.js): keys the cart accepts, monthly prices as decimals. */
    private function panelCatalog(string $locale): array
    {
        $out = [];
        $registry = app(ProviderRegistry::class);
        $placements = app(PlacementService::class);
        $executors = Product::query()->whereIn('state', ['active'])->pluck('executor', 'key')->all();
        // a category staff switched off in the sidebar settings sells nothing new (existing services stay manageable)
        $categoryOrderable = [];
        foreach (app(PanelNavigation::class)->effective(null)['categories'] as $category) {
            $categoryOrderable[$category['key']] = $category['orderable'];
        }
        foreach ($this->catalog->publicCatalog($locale, 'CZK') as $product) {
            $plans = [];
            foreach ((array) ($product['plans'] ?? []) as $plan) {
                if (! isset($plan['price']['month'])) {
                    continue;
                }
                $plans[] = ['key' => $plan['key'], 'name' => (string) $plan['name'], 'spec' => (string) ($plan['description'] ?? ''), 'monthly' => self::amount($plan['price']['month']), 'yearly' => isset($plan['price_year']['year']) ? self::amount($plan['price_year']['year']) : null, 'highlighted' => (bool) ($plan['highlighted'] ?? false)];
            }
            if ($plans === []) {
                continue;
            }
            // an executor without a usable instance or placement cannot be provisioned: the wizard lists the product as "on request"
            $executor = $executors[$product['key']] ?? null;
            $orderable = $executor === null || $executor === '' || $placements->resolve($product['key'], null, null) !== null || $registry->findInstance((string) $executor) !== null;
            $category = PanelNavigation::categoryFor((string) $product['family'], (string) $product['key'], $executor);
            $orderable = $orderable && ($category === null || ($categoryOrderable[$category] ?? true));
            // game servers: the templates the product sells (Product.meta.eggs) with the presets' labels — the wizard's "Systém a obraz" step offers them
            $eggs = [];
            foreach ((array) data_get($product, 'meta.eggs', []) as $eggKey) {
                $preset = (array) config("onhost.game.eggs.{$eggKey}", []);
                $eggs[] = ['key' => (string) $eggKey, 'label' => (string) ($preset['label'] ?? $eggKey), 'note' => (string) ($preset['note'] ?? ''), 'min_ram_mb' => (int) ($preset['min_ram_mb'] ?? 0), 'versions' => array_values(array_map('strval', (array) ($preset['versions'] ?? [])))]; // §5p: the versions a template offers in the wizard
            }
            $out[] = ['key' => $product['key'], 'family' => $product['family'], 'category' => $category, 'name' => (string) $product['name'], 'description' => (string) ($product['description'] ?? ''), 'plans' => $plans, 'orderable' => $orderable, 'eggs' => $eggs];
        }

        return $out;
    }

